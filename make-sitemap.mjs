// Rebuilds sitemap.xml with every live ad, category page and seller, so Google can find new ads.
//
//   node tools/make-sitemap.mjs https://yourdomain.com
//
// Run it before each deploy (and after the domain changes). It reads only public data (approved, unexpired ads),
// the same data any visitor can see. Then deploy:  firebase deploy --only hosting
// Needs Node 18 or newer. Nothing is installed.
const SITE = (process.argv[2] || "https://fexiwalt.com").replace(/\/+$/, "");
const PROJECT = "flexiwalt";
const EXPIRY_DAYS = 60;   // keep in sync with js/core/util.js

const CATEGORIES = ["Electronics", "Mobile Phones & Tablets", "Vehicles", "Property", "Fashion", "Home & Furniture", "Health & Beauty", "Jobs", "Services", "Others"];
const esc = s => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const today = new Date().toISOString().slice(0, 10);

// ask Firestore (REST) for approved ads
const res = await fetch(`https://firestore.googleapis.com/v1/projects/${PROJECT}/databases/(default)/documents:runQuery`, {
  method: "POST", headers: { "Content-Type": "application/json" },
  body: JSON.stringify({ structuredQuery: { from: [{ collectionId: "ads" }], where: { fieldFilter: { field: { fieldPath: "status" }, op: "EQUAL", value: { stringValue: "approved" } } }, limit: 5000 } })
});
if (!res.ok) { console.error("Couldn't read ads:", res.status, await res.text()); process.exit(1); }
const rows = (await res.json()).filter(r => r.document);

const now = Date.now(), ads = [], sellers = new Set();
for (const { document: d } of rows) {
  const f = d.fields || {};
  const created = f.createdAt?.timestampValue ? Date.parse(f.createdAt.timestampValue) : now;
  const expires = f.expiresAt?.timestampValue ? Date.parse(f.expiresAt.timestampValue) : created + EXPIRY_DAYS * 864e5;
  if (expires < now) continue;   // expired: leave it out
  ads.push({ id: d.name.split("/").pop(), lastmod: new Date(d.updateTime || created).toISOString().slice(0, 10) });
  if (f.sellerId?.stringValue) sellers.add(f.sellerId.stringValue);
}

const url = (path, freq, prio, lastmod = today) => `  <url><loc>${esc(SITE + path)}</loc><lastmod>${lastmod}</lastmod><changefreq>${freq}</changefreq><priority>${prio}</priority></url>`;
const out = [
  `<?xml version="1.0" encoding="UTF-8"?>`,
  `<!-- Generated by tools/make-sitemap.mjs on ${today}. Do not edit by hand: re-run the script. -->`,
  `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">`,
  url("/", "daily", "1.0"),
  url("/category.html?all=1", "daily", "0.9"),
  ...CATEGORIES.map(c => url(`/category.html?cat=${encodeURIComponent(c)}`, "daily", "0.8")),
  url("/sellers.html", "weekly", "0.6"),
  ...[...sellers].map(s => url(`/seller.html?id=${encodeURIComponent(s)}`, "weekly", "0.5")),
  ...ads.map(a => url(`/ad.html?id=${encodeURIComponent(a.id)}`, "weekly", "0.7", a.lastmod)),
  url("/help.html", "monthly", "0.5"), url("/contact.html", "monthly", "0.4"),
  url("/terms.html", "yearly", "0.3"), url("/privacy.html", "yearly", "0.3"),
  `</urlset>`, ""
].join("\n");

const { writeFileSync } = await import("node:fs");
const { fileURLToPath } = await import("node:url");
writeFileSync(fileURLToPath(new URL("../sitemap.xml", import.meta.url)), out);
console.log(`sitemap.xml written: ${ads.length} ads, ${sellers.size} sellers, ${CATEGORIES.length} categories  ->  ${SITE}`);
